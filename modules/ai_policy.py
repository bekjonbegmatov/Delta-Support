class SupportAnswer(str):
    def __new__(cls, text, *, offer_manager=False):
        value = super().__new__(cls, text)
        value.offer_manager = offer_manager
        return value


def explicitly_requests_manager(question):
    text = " ".join((question or "").casefold().replace("ё", "е").split())
    if re.search(
        r"\b(?:без\s+|не\s+(?:хочу|нужен|нужна|зовите|вызывайте|приглашайте|подключайте)\s+|"
        r"не\s+(?:надо|нужно)\s+(?:(?:приглашать|вызывать|звать|подключать)\s+)?)"
        r"(?:менеджер\w*|оператор\w*|человек\w*)\b", text,
    ):
        return False
    if re.search(r"\b(?:менеджер\s+парол|диспетчер\s+задач)", text):
        return False
    if re.fullmatch(r"(?:пожалуйста[, ]+)?(?:менеджер[а]?|оператор[а]?|живой человек|живого человека)[.!? ]*", text):
        return True
    return bool(re.search(
        r"\b(?:позовите|позови|пригласите|пригласи|вызовите|вызови|соедините|соедини|переключите|подключите|хочу|нужен|нужна|можно)\b"
        r"[^.!?]{0,45}\b(?:менеджер\w*|оператор\w*|человек\w*|живую поддержку)\b"
        r"|\b(?:connect|speak|talk|need|want)\b[^.!?]{0,45}\b(?:human|agent|operator|manager)\b", text,
    ))


def should_offer_manager(answer, question=""):
    return bool(getattr(answer, "offer_manager", False) or explicitly_requests_manager(question))


def validate_manager_offer(args, question, history):
    reason = args.get("reason")
    code = args.get("reason_code")
    if not isinstance(reason, str) or len(reason.strip()) < 12:
        return False
    if code == "customer_request":
        return explicitly_requests_manager(question)
    if code == "manual_action_required":
        return True
    if code == "diagnostics_exhausted":
        return sum(msg.get("role") == "assistant" for msg in (history or [])) >= 2
    return False
